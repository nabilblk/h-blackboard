import { readFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

export function applyDisruption(input, change) {
  if (input.revision !== change.supersedes)
    throw new Error("The disruption does not apply to this input revision.");
  const next = structuredClone(input);
  next.revision = change.revision;
  next.rooms.find((r) => r.id === "lab").closures.push(change.lab_closure);
  next.activities.find((a) => a.id === "robots").not_before =
    change.robots_not_before;
  next.costs.find((c) => c.id === "robots").unit_cost_cents =
    change.robots_cost_cents;
  return next;
}

// Independent outcome check. Never imports or executes an agent's files.
// Fixed input files are maintained by the experiment, not generated by agents.
export function checkPlan(input, schedule, budget) {
  const errors = [];
  const add = (code, detail) => errors.push({ code, detail });
  const rows = schedule?.sessions;
  if (schedule?.input_revision !== input.revision)
    add("schedule_revision", "Schedule cites a superseded or missing input.");
  if (budget?.input_revision !== input.revision)
    add("budget_revision", "Budget cites a superseded or missing input.");
  if (!Array.isArray(rows) || rows.length !== input.activities.length)
    add("coverage", "Schedule every activity exactly once.");
  const sessions = [];
  const seen = new Set();
  for (const row of (Array.isArray(rows) ? rows : []).slice(0, 256)) {
    const activity = input.activities.find((a) => a.id === row?.activity);
    const room = input.rooms.find((r) => r.id === row?.room);
    if (!activity || !room || !Number.isSafeInteger(row?.start)) {
      add("session_shape", "Unknown activity/room or non-integer start time.");
      continue;
    }
    if (seen.has(activity.id)) add("coverage", `Duplicate ${activity.id}.`);
    seen.add(activity.id);
    const end = row.start + activity.duration;
    const start = row.start;
    const setup = start - input.setup_minutes;
    const facilitator = input.facilitators.find(
      (f) => f.id === activity.facilitator,
    );
    if (
      setup < input.opens ||
      end > input.closes ||
      start < (activity.not_before ?? 0)
    )
      add(
        "hours",
        `${activity.id} is outside its allowed hours (including room setup).`,
      );
    if (
      !activity.rooms.includes(room.id) ||
      room.capacity < activity.attendance
    )
      add("room", `${activity.id} uses an unsuitable room.`);
    if (room.closures.some((c) => setup < c.until && end > c.from))
      add(
        "closure",
        `${activity.id} overlaps a room closure or its setup does.`,
      );
    if (start < facilitator.from || end > facilitator.until)
      add(
        "facilitator_hours",
        `${activity.id} is outside facilitator availability.`,
      );
    sessions.push({ activity, room, start, setup, end });
  }
  for (const activity of input.activities) {
    if (!seen.has(activity.id)) add("coverage", `Missing ${activity.id}.`);
  }
  for (let i = 0; i < sessions.length; i++) {
    const a = sessions[i];
    for (const dependency of a.activity.after) {
      const previous = sessions.find((s) => s.activity.id === dependency);
      if (!previous || previous.end > a.start)
        add("dependency", `${a.activity.id} must follow ${dependency}.`);
    }
    for (const b of sessions.slice(i + 1)) {
      if (a.room.id === b.room.id && a.setup < b.end && b.setup < a.end)
        add(
          "room_overlap",
          `${a.activity.id} / ${b.activity.id}: room and setup conflict.`,
        );
      if (
        a.activity.facilitator === b.activity.facilitator &&
        a.start < b.end &&
        b.start < a.end
      )
        add(
          "facilitator_overlap",
          `${a.activity.id} / ${b.activity.id}: facilitator conflict.`,
        );
    }
  }
  // Resources are needed during activities only; room setup needs neither the
  // facilitator nor extra volunteers/kits. Half-open intervals permit handoff.
  for (const time of new Set(sessions.map((s) => s.start))) {
    const active = sessions.filter((s) => s.start <= time && s.end > time);
    if (
      active.reduce((n, s) => n + s.activity.volunteers, 0) > input.volunteers
    )
      add("volunteers", `Volunteer capacity exceeded at minute ${time}.`);
    for (const [resource, capacity] of Object.entries(input.equipment)) {
      if (
        active.reduce((n, s) => n + (s.activity.equipment[resource] ?? 0), 0) >
        capacity
      )
        add("equipment", `${resource} capacity exceeded at minute ${time}.`);
    }
  }
  const items = budget?.items;
  if (!Array.isArray(items) || items.length !== input.costs.length)
    add("cost_coverage", "Include every supplied cost exactly once.");
  for (const cost of input.costs) {
    const matches = (Array.isArray(items) ? items : []).filter(
      (i) => i?.id === cost.id,
    );
    if (
      matches.length !== 1 ||
      matches[0].quantity !== cost.quantity ||
      matches[0].unit_cost_cents !== cost.unit_cost_cents
    )
      add("cost", `Incorrect or missing ${cost.id} cost.`);
  }
  const subtotal = input.costs.reduce(
    (n, i) => n + i.quantity * i.unit_cost_cents,
    0,
  );
  const reserve = Math.ceil((subtotal * input.reserve_percent) / 100);
  if (
    budget?.subtotal_cents !== subtotal ||
    budget?.reserve_cents !== reserve ||
    budget?.total_cents !== subtotal + reserve
  )
    add("totals", "Budget subtotal, reserve or total is incorrect.");
  if (subtotal + reserve > input.spending_cap_cents)
    add("spending_cap", "The required costs exceed the spending cap.");
  return {
    passed: errors.length === 0,
    input_revision: input.revision,
    errors,
  };
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const paths = process.argv.slice(2);
  if (paths.length !== 3) {
    console.error(
      "Usage: node experiments/community-day/check.mjs INPUT.json SCHEDULE.json BUDGET.json",
    );
    process.exitCode = 2;
  } else {
    try {
      const values = await Promise.all(
        paths.map(async (p) => JSON.parse(await readFile(p, "utf8"))),
      );
      const result = checkPlan(...values);
      console.log(JSON.stringify(result, null, 2));
      process.exitCode = result.passed ? 0 : 1;
    } catch (error) {
      console.error(`Invalid experiment input: ${error.message}`);
      process.exitCode = 2;
    }
  }
}
